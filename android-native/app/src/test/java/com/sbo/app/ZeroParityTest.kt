import org.junit.Test
import java.time.LocalDate

/** The native Progetto Zero plan must equal the website's (fixtures generated by running src/lib/sbo-zero.ts in Node). */
class ZeroParityTest {
    private val json = Json { ignoreUnknownKeys = true }
    private fun num(d: Double) = if (d == Math.floor(d)) d.toLong().toString() else d.toString()

    @Test fun plansMatchWeb() {
        val text = javaClass.classLoader!!.getResource("zero-fixtures.json")!!.readText()
        val cases = json.parseToJsonElement(text).jsonArray
        var bad = 0
        val report = StringBuilder()
        for (c in cases) {
            val o = c.jsonObject
            val a = json.decodeFromJsonElement<ZeroAnswers>(o["a"] as JsonObject)
            val league = Zero.computeLeague(a)
            assertEquals(o["league"]!!.jsonPrimitive.content, league.name)
            assertEquals(o["td"]!!.jsonArray.map { it.jsonPrimitive.int }, Zero.trainingDays(league, a))
            val day = LocalDate.parse(o["day"]!!.jsonPrimitive.content)
            val p = Zero.planForDay(day, league, a, LocalDate.of(2026, 9, 1), o["seed"]!!.jsonPrimitive.content)
            val ex = p.exercises.map { "${it.name}|${it.sets}|${num(it.amount)}|${it.unit}" }
            val want = o["ex"]!!.jsonArray.map { it.jsonPrimitive.content }
            val ok = p.title == o["title"]!!.jsonPrimitive.content && p.rest == o["rest"]!!.jsonPrimitive.booleanOrNull &&
                p.restTip == o["restTip"]!!.jsonPrimitive.contentOrNull && p.intensity == o["intensity"]!!.jsonPrimitive.contentOrNull && ex == want
            if (!ok) { bad++; report.append("$day ${o["seed"]}: got ${p.title} ${p.intensity} $ex, want ${o["title"]} ${o["intensity"]} $want\n") }
        }
        assertEquals("plans differing from the web:\n$report", 0, bad)
    }
}
