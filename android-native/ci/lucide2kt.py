"""Converts Lucide SVG icons (24x24, stroke 2, round caps/joins) into Compose ImageVectors."""
import sys, re, xml.etree.ElementTree as ET
src, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]

def f(v): return float(v)
def to_path(el):
    tag = el.tag.split('}')[-1]; a = el.attrib
    if tag == 'path': return a['d']
    if tag == 'circle':
        cx, cy, r = f(a['cx']), f(a['cy']), f(a['r'])
        return f"M{cx-r},{cy}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0"
    if tag == 'ellipse':
        cx, cy, rx, ry = f(a['cx']), f(a['cy']), f(a['rx']), f(a['ry'])
        return f"M{cx-rx},{cy}a{rx},{ry} 0 1,0 {2*rx},0a{rx},{ry} 0 1,0 {-2*rx},0"
    if tag == 'line': return f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}"
    if tag in ('polyline', 'polygon'):
        pts = re.findall(r'-?[\d.]+', a['points']); pairs = [f"{pts[i]},{pts[i+1]}" for i in range(0, len(pts), 2)]
        return 'M' + 'L'.join(pairs) + ('Z' if tag == 'polygon' else '')
    if tag == 'rect':
        x, y, w, h = f(a.get('x', 0)), f(a.get('y', 0)), f(a['width']), f(a['height'])
        rx = f(a.get('rx', a.get('ry', 0))); ry = f(a.get('ry', rx))
        if rx == 0: return f"M{x},{y}h{w}v{h}h{-w}Z"
        return (f"M{x+rx},{y}h{w-2*rx}a{rx},{ry} 0 0 1 {rx},{ry}v{h-2*ry}a{rx},{ry} 0 0 1 {-rx},{ry}"
                f"h{-(w-2*rx)}a{rx},{ry} 0 0 1 {-rx},{-ry}v{-(h-2*ry)}a{rx},{ry} 0 0 1 {rx},{-ry}Z")
    return None

lines = ["package com.sbo.app.ui", "", "// Generated by ci/lucide2kt.py from lucide-static (same icons as the website).",
         "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.graphics.SolidColor",
         "import androidx.compose.ui.graphics.StrokeCap", "import androidx.compose.ui.graphics.StrokeJoin",
         "import androidx.compose.ui.graphics.vector.ImageVector", "import androidx.compose.ui.graphics.vector.PathParser",
         "import androidx.compose.ui.unit.dp", "",
         "private fun lucide(name: String, stroke: Float, vararg d: String): ImageVector {",
         "    val b = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f)",
         "    for (p in d) b.addPath(PathParser().parsePathString(p).toNodes(), stroke = SolidColor(Color.White), strokeLineWidth = stroke, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)",
         "    return b.build()", "}", "", "object Lucide {"]
for spec in names:
    n, _, sw = spec.partition(':')
    root = ET.parse(f"{src}/{n}.svg").getroot()
    ds = [to_path(e) for e in root.iter() if to_path(e)]
    ident = ''.join(p.capitalize() for p in n.split('-')) + ('Bold' if sw else '')
    args = ', '.join('"' + d.replace('"', '') + '"' for d in ds)
    lines.append(f'    val {ident}: ImageVector by lazy {{ lucide("{n}", {sw or "2"}f, {args}) }}')
lines.append("}")
open(out, 'w').write('\n'.join(lines) + '\n')
print("icons:", len(names))
